                </h3>
                <div id="sop1" class="accordion-collapse collapse" data-bs-parent="#sopAccordion">
                    <div class="accordion-body">
                        <ul class="mb-0">
                            <li class="mb-2"><strong>Jam Kerja &amp; Presensi:</strong> Wajib melakukan presensi masuk dan pulang sesuai ketentuan jam kerja Aparatur Sipil Negara (ASN) / Pegawai Pemerintah yang berlaku. Keterlambatan atau ketidakhadiran tanpa keterangan sah dikenakan sanksi disiplin.</li>
                            <li class="mb-2"><strong>Pakaian Dinas &amp; Atribut:</strong> Menggunakan Pakaian Dinas Harian (PDH) sesuai jadwal harian beserta kelengkapan atribut (tanda pengenal/ID card, pin logo daerah).</li>
                            <li class="mb-0"><strong>Etika Pelayanan (5S):</strong> Menerapkan Senyum, Salam, Sapa, Sopan, dan Santun kepada seluruh warga, penerima manfaat, maupun pemangku kepentingan tanpa diskriminasi.</li>
                        </ul>
                    </div>
