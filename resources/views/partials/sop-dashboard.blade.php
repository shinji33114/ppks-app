                            <li class="mb-0"><strong>Evaluasi Bulanan:</strong> Setiap awal bulan, Kepala Bidang menggelar rapat koordinasi internal untuk mengevaluasi pencapaian target Standar Pelayanan Minimal (SPM) bidang sosial dan tindak lanjut aduan masyarakat.</li>
                        </ul>
