            <div class="accordion-item">
                <h3 class="accordion-header">
                    <button class="accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#sop2">
                        2. SOP Pelayanan Informasi &amp; Pengaduan Masyarakat
                    </button>
                </h3>
                <div id="sop2" class="accordion-collapse collapse" data-bs-parent="#sopAccordion">
                    <div class="accordion-body">
                        <ol class="mb-3">
                            <li class="mb-2"><strong>Penerimaan Pemohon:</strong> Petugas Front Office menyapa warga, menanyakan maksud kedatangan, dan mencatat identitas pemohon ke dalam buku register / aplikasi sistem pelayanan.</li>
                            <li class="mb-2"><strong>Pemeriksaan Dokumen:</strong> Petugas memeriksa kelengkapan berkas administrasi dasar (KTP, KK, Surat Keterangan Tidak Mampu/SKTM dari desa/kelurahan).</li>
                            <li class="mb-2"><strong>Pengecekan Data (DTKS / SIKS-NG):</strong> Petugas melakukan verifikasi NIK pemohon pada basis data terpadu untuk memastikan status kepesertaan bantuan sosial (PBI-JK, PKH, BPNT, dll.).</li>
                            <li class="mb-2">
                                <strong>Pemberian Solusi / Rujukan:</strong>
                                <ul class="mt-1">
                                    <li><strong>Lengkap:</strong> Berkas diteruskan ke bidang teknis terkait (Rehabilitasi Sosial, Perlindungan dan Jaminan Sosial, atau Pemberdayaan Sosial) untuk pemrosesan rekomendasi/surat keterangan.</li>
                                    <li><strong>Tidak Lengkap:</strong> Petugas memberikan lembar kontrol kekurangan berkas dan menjelaskan prosedur pemenuhannya secara jelas.</li>
                                </ul>
                            </li>
                            <li class="mb-0"><strong>Estimasi Waktu:</strong> Pelayanan konsultasi dan verifikasi awal diselesaikan maksimal 15–20 menit per pemohon.</li>
                        </ol>
                    </div>
                </div>
            </div>

            <div class="accordion-item">
                <h3 class="accordion-header">
                    <button class="accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#sop3">
                        3. SOP Penanganan Pemerlu Pelayanan Kesejahteraan Sosial (PPKS)
                    </button>
                </h3>
                <div id="sop3" class="accordion-collapse collapse" data-bs-parent="#sopAccordion">
                    <div class="accordion-body">
                        <ol class="mb-0">
                            <li class="mb-2"><strong>Penerimaan Laporan / Penjangkauan (Outreach):</strong> Petugas/Tim Reaksi Cepat menerima laporan dari masyarakat, kepolisian, Satpol PP, atau hasil patroli lapangan mengenai penanganan PPKS (lansia terlantar, anak jalanan, gelandangan, pengemis, ODGJ).</li>
                            <li class="mb-2"><strong>Asesmen Awal &amp; Pendataan:</strong> Pekerja Sosial (Peksos) / Pendamping melakukan asesmen kondisi fisik, psikologis, dan latar belakang sosial keluarga korban.</li>
                            <li class="mb-2">
                                <strong>Tindakan Lanjut &amp; Penanganan:</strong>
                                <ul class="mt-1">
                                    <li><strong>Layanan Medis Darurat:</strong> Merujuk PPKS ke puskesmas/RSUD jika membutuhkan penanganan medis segera.</li>
                                    <li><strong>Penampungan Sementara:</strong> Mengarahkan PPKS ke Rumah Singgah / Panti Sosial untuk perlindungan awal.</li>
                                    <li><strong>Reunifikasi Keluarga:</strong> Menelusuri alamat asal dan memfasilitasi pemulangan PPKS ke keluarga atau daerah asal secara sah.</li>
                                </ul>
                            </li>
                            <li class="mb-0"><strong>Penyusunan Berita Acara:</strong> Petugas menyusun Berita Acara Penanganan (BAP) dan menginput data ke dalam basis data PPKS Dinas Sosial.</li>
                        </ol>
                    </div>
                </div>
            </div>

            <div class="accordion-item">
                <h3 class="accordion-header">
                    <button class="accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#sop4">
                        4. SOP Verifikasi &amp; Penyaluran Bantuan Sosial
                    </button>
                </h3>
                <div id="sop4" class="accordion-collapse collapse" data-bs-parent="#sopAccordion">
                    <div class="accordion-body">
                        <ol class="mb-0">
                            <li class="mb-2"><strong>Penerimaan Usulan:</strong> Mengompilasi data usulan calon penerima bantuan dari Musyawarah Desa/Kelurahan (Musdes/Muskel).</li>
                            <li class="mb-2"><strong>Verifikasi Faktual (Ground Checking):</strong> Petugas pendamping lapangan melakukan survei dan validasi kondisi faktual ekonomi serta tempat tinggal calon penerima bantuan.</li>
                            <li class="mb-2"><strong>Penginputan Data:</strong> Operator SIKS-NG mengunggah data hasil validasi ke dalam sistem kementerian / sistem pemerintah daerah.</li>
                            <li class="mb-2"><strong>Penerbitan Rekomendasi:</strong> Kepala Bidang memeriksa kelayakan data dan Kepala Dinas menandatangani Lembar Pengesahan / Surat Rekomendasi Penyaluran.</li>
                            <li class="mb-0"><strong>Monitoring Penyaluran:</strong> Petugas melakukan pengawasan saat pembagian bantuan (tunai/non-tunai) untuk memastikan ketepatan sasaran, jumlah, dan waktu.</li>
                        </ol>
                    </div>
                </div>
            </div>

            <div class="accordion-item">
                <h3 class="accordion-header">
                    <button class="accordion-button collapsed" type="button" data-bs-toggle="collapse" data-bs-target="#sop5">
                        5. SOP Penanganan Tanggap Darurat Bencana (TAGANA &amp; Logistik)
                    </button>
                </h3>
                <div id="sop5" class="accordion-collapse collapse" data-bs-parent="#sopAccordion">
                    <div class="accordion-body">
                        <ol class="mb-0">
                            <li class="mb-2"><strong>Penerimaan Informasi Bencana:</strong> Petugas siaga bencana menerima laporan kejadian bencana alam/sosial dari BPBD, pihak kecamatan, atau warga.</li>
                            <li class="mb-2"><strong>Mobilisasi Tim &amp; Logistik:</strong> Menginstruksikan personil Taruna Siaga Bencana (TAGANA) dan menyiapkan bantuan logistik darurat (makanan siap saji, tenda, selimut, peralatan dapur keluarga) dari gudang logistik.</li>
                            <li class="mb-2"><strong>Pendirian Dapur Umum &amp; Posko:</strong> Membuka Dapur Umum Lapangan (Dumlap) dan membagikan bantuan bahan pokok di lokasi pengungsian dalam waktu maksimal 3x24 jam sejak masa tanggap darurat ditetapkan.</li>
                            <li class="mb-0"><strong>Pelaporan Logistik:</strong> Petugas membuat Laporan Penyaluran Logistik dan Laporan Pertanggungjawaban (LPJ) stok bantuan.</li>
                        </ol>
                    </div>
                </div>
